async def analyze_plan(
    plan_name: str,
    plan_type: str,
    target_audience: Optional[str],
    content_text: str
) -> str:
    """
    分析策划方案的舆情风险

    Args:
        plan_name: 方案名称
        plan_type: 方案类型
        target_audience: 目标受众
        content_text: 方案详细内容

    Returns:
        结构化的风险评估报告（Markdown格式）
    """
    logger.info("开始分析策划方案: {}", plan_name)

    # 构建用户消息
    user_message = f"""## 待分析方案信息

**方案名称**：{plan_name}
**方案类型**：{plan_type}
**目标受众**：{target_audience or '未指定'}

---

## 方案详细内容

{content_text or '（无详细描述）'}

---

请按照10维度框架，对以上策划方案进行完整的舆情风险评估。"""

    try:
        # 调用百炼模型进行分析
        report = await chat_with_ai(
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_message}
            ],
            enable_search=False,
            model="qwen-plus"  # 使用更强的模型以获得更详细的分析
        )

        # 清理响应，移除可能的思考过程或额外输出
        report = clean_report(report)

        logger.info("方案分析完成: {}, 报告长度: {} 字符", plan_name, len(report))
        return report

    except Exception as e:
        logger.error("方案分析失败: {}", e)
        raise


def clean_report(report: str) -> str:
    """
    清理报告输出，移除可能的干扰内容
    """
    # 移除常见的AI思考过程标记
    patterns_to_remove = [
        r'```thinking[\s\S]*?```',
        r'<!--[\s\S]*?-->',
        r'\[思考过程\][\s\S]*?\[/思考过程\]',
    ]

    cleaned = report
    for pattern in patterns_to_remove:
        cleaned = re.sub(pattern, '', cleaned)

    # 移除首尾空白
    cleaned = cleaned.strip()

    # 确保报告以标题开始
    if not cleaned.startswith('#'):
        # 尝试找到第一个标题位置
        match = re.search(r'#.*', cleaned)
        if match:
            cleaned = cleaned[match.start():]

    return cleaned


def extract_risk_score(report: str, dimension: str) -> Optional[int]:
    """
    从报告中提取特定维度的风险评分

    Args:
        report: 分析报告文本
        dimension: 维度名称

    Returns:
        风险评分（0-100），如果未找到返回None
    """
    # 尝试匹配 "维度名称 | XX" 格式
    pattern = rf'{dimension}.*?(\d{{1,3}})'
    match = re.search(pattern, report)

    if match:
        try:
            score = int(match.group(1))
            if 0 <= score <= 100:
                return score
        except ValueError:
            pass

    return None


def extract_overall_risk_level(report: str) -> str:
    """
    从报告中提取总体风险等级

    Args:
        report: 分析报告文本

    Returns:
        风险等级（高/中/低）
    """
    if '总体风险等级' in report or '综合风险等级' in report:
        if '高风险' in report:
            return '高'
        elif '中风险' in report:
            return '中'
        elif '低风险' in report:
            return '低'

    return '未知'
